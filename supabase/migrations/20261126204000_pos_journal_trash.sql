-- Journal Report ゴミ箱テーブル: POS原本(pos_journal_files)や店舗資料(store_knowledge_documents)を
-- 直接完全削除せず、ゴミ箱へ退避して移動日時(trashed_at)を記録し、一覧閲覧・復元・ゴミ箱からの完全削除を可能にする。
-- 公開Pages/クライアントは直接参照せず、service_roleを使うadmin-apiのみが操作する。

create table if not exists public.pos_journal_trash (
  id bigint generated by default as identity primary key,
  store_partition_key text not null,
  item_kind text not null check (item_kind in ('pos_journal_file', 'store_knowledge_document')),
  original_id text not null,
  title text not null check (length(btrim(title)) > 0),
  subtitle text not null default '',
  target_month text,
  business_date date,
  storage_bucket text,
  storage_path text,
  original_row jsonb not null,
  related_rows jsonb not null default '[]'::jsonb,
  trashed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint pos_journal_trash_unique_original unique (store_partition_key, item_kind, original_id)
);

create index if not exists pos_journal_trash_store_kind_trashed_idx
  on public.pos_journal_trash (store_partition_key, item_kind, trashed_at desc, id desc);

create index if not exists pos_journal_trash_store_trashed_idx
  on public.pos_journal_trash (store_partition_key, trashed_at desc, id desc);

alter table public.pos_journal_trash enable row level security;
revoke all on table public.pos_journal_trash from public, anon, authenticated;
grant select, insert, update, delete on table public.pos_journal_trash to service_role;

comment on table public.pos_journal_trash is
  'Journal Report ゴミ箱（POS原本・店舗資料の退避先）。ゴミ箱への移動日時(trashed_at)と復元用スナップショットを保持。admin-api 経由のみ。';
comment on column public.pos_journal_trash.item_kind is
  '退避元の種別: pos_journal_file（POS原本） / store_knowledge_document（店舗資料）。';
comment on column public.pos_journal_trash.trashed_at is
  'ゴミ箱へ移動された日時（UTC保存・画面ではJST表示）。';
comment on column public.pos_journal_trash.original_row is
  '復元時に元テーブルへ戻すための全カラムスナップショット。';
comment on column public.pos_journal_trash.related_rows is
  '資料のRAGチャンクなど、関連テーブル行のバックアップ配列。';
