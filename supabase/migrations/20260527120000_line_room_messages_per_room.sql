-- ルーム別トーク保存・1年保持・全文断片検索（pg_trgm）・横断検索インデックス

create extension if not exists pg_trgm;

-- ---------------------------------------------------------------------------
-- Registry: room_id → per-room message table
-- ---------------------------------------------------------------------------

create table if not exists public.line_room_message_tables (
  room_id text primary key,
  message_table text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.line_room_message_tables is
  'LINE room_id ごとのトーク保存テーブル名レジストリ（line_messages__*）';

create or replace function public.is_valid_line_room_id(p_room_id text)
returns boolean
language sql
immutable
as $$
  select coalesce(p_room_id, '') ~ '^[A-Za-z0-9][A-Za-z0-9_-]{0,120}$';
$$;

create or replace function public.line_room_message_table_name(p_room_id text)
returns text
language sql
immutable
as $$
  select 'line_messages__r' || substr(md5(p_room_id), 1, 16);
$$;

-- ---------------------------------------------------------------------------
-- Global search index (room-scoped + cross-room queries)
-- ---------------------------------------------------------------------------

create table if not exists public.line_room_messages_search (
  id bigint generated by default as identity primary key,
  room_id text not null,
  room_message_id bigint not null,
  message_table text not null,
  line_message_id text,
  webhook_event_id text,
  user_id text,
  message_type text not null default 'unknown',
  text_content text not null default '',
  created_at timestamptz not null default now()
);

comment on table public.line_room_messages_search is
  '会話検索用インデックス（最大1年）。ルーム別テーブルと二重書き込み。';

create unique index if not exists line_room_messages_search_room_msg_uidx
  on public.line_room_messages_search (message_table, room_message_id);

create index if not exists line_room_messages_search_room_created_idx
  on public.line_room_messages_search (room_id, created_at desc);

create index if not exists line_room_messages_search_created_idx
  on public.line_room_messages_search (created_at desc);

create index if not exists line_room_messages_search_text_trgm_idx
  on public.line_room_messages_search using gin (text_content gin_trgm_ops);

