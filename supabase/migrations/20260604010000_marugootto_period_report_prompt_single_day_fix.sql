-- マルゴオット（marugootto）の期間集計レポート判定プロンプトを是正。
-- 背景: 単日の「日計精算レポート（店舗合計）取引別」（営業日付＝1日）を、AIが
--   「期間集計レポート」と誤判定し、売上登録されず「登録していません」返信になった。
--   原因は前版(040000)の判定条件が OR で「構成比」を含み、日計レポートにも必ず付く
--   「構成比」「店舗合計」「取引別」だけで期間集計と誤認したため。
-- 対策: 単一日（日計／営業日付が1日）のレポートは、たとえ店舗合計・取引別・構成比・客単価が
--   あっても必ず kind="receipt" として売上登録する。期間集計と判定してよいのは
--   「期間」「日付範囲」「開始〜終了の異なる2つの日付」が明示された複数日集計のみに限定する。
--   期間集計時の summary マーカー「期間集計レポート」要件は従来どおり維持
--   （line-webhook の検知正規表現 /期間集計|.../ がこれを拾う）。

insert into public.store_receipt_analysis_prompts (store_partition_key, prompt, enabled, updated_at)
values (
  'marugootto',
  $prompt$この店舗では、通常の1会計レシートのほかに、POSの「日計精算レポート（その日1日の精算）」や「期間集計レポート（複数日＝期間／日付範囲の合計）」の画像が送られてきます。これらを必ず正しく区別してください。

【最重要1：日計＝売上レシートとして扱う】次のいずれかに当てはまるものは、その日の売上レシートです。必ず kind="receipt" として通常どおり解析し、主要項目（store_name・date・売上・組数/客数など）を抽出してください:
・タイトルや見出しに「日計」「日計精算」「日報」が含まれる
・「営業日付」「営業日」が単一の1日だけ（例: 2026年6月3日）になっている
※「店舗合計」「取引別」「構成比」「客単価」などの語や、内訳の％（構成比）表示があっても、対象が単一日なら必ず日計＝レシートです。これらの語だけで「期間集計」と判定してはいけません。

【最重要2：期間集計＝登録しない】複数日にわたる集計、すなわち「期間」「日付範囲」「開始〜終了の異なる2つの日付」が明示されている場合のみ、期間集計レポートとして次のJSONにしてください:
・kind は "general"（絶対に "receipt" にしない）
・receipt は null
・summary は必ず「期間集計レポート：このレシートは日々の売上ではないため登録していません」という文字列にする。先頭は必ず「期間集計レポート」とし、言い換え・要約・省略・翻訳は禁止。

迷う場合は、対象が単一日なら日計（kind="receipt"・売上登録する）を優先してください。$prompt$,
  true,
  now()
)
on conflict (store_partition_key) do update
  set prompt = excluded.prompt,
      enabled = true,
      updated_at = now();
