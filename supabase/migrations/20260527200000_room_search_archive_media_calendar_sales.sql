create or replace function public.insert_line_room_media_search(
  p_room_id text,
  p_line_message_id text default null,
  p_user_id text default null,
  p_media_type text default 'unknown',
  p_original_file_name text default null,
  p_content_preview text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  row_id bigint;
  preview text;
begin
  if not public.is_valid_line_room_id(p_room_id) then
    raise exception 'invalid room_id: %', p_room_id;
  end if;
  preview := coalesce(btrim(p_content_preview), '');
  if preview = '' and coalesce(btrim(p_original_file_name), '') = '' then
    return null;
  end if;
  insert into public.line_room_media_search (
    room_id, line_message_id, user_id, media_type, original_file_name, content_preview
  ) values (
    p_room_id,
    nullif(btrim(p_line_message_id), ''),
    nullif(btrim(p_user_id), ''),
    coalesce(nullif(btrim(p_media_type), ''), 'unknown'),
    nullif(btrim(p_original_file_name), ''),
    coalesce(preview, coalesce(btrim(p_original_file_name), ''))
  )
  on conflict (line_message_id) where line_message_id is not null
  do update set
    content_preview = excluded.content_preview,
    original_file_name = excluded.original_file_name,
    media_type = excluded.media_type
  returning id into row_id;
  return row_id;
end;
$$;

create or replace function public.insert_line_room_calendar_search(
  p_room_id text,
  p_line_message_id text default null,
  p_event_title text default '',
  p_event_description text default '',
  p_starts_at timestamptz default null,
  p_source text default 'line_talk'
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  row_id bigint;
  title text;
  body text;
begin
  if not public.is_valid_line_room_id(p_room_id) then
    raise exception 'invalid room_id: %', p_room_id;
  end if;
  title := coalesce(btrim(p_event_title), '');
  body := coalesce(btrim(p_event_description), '');
  if title = '' and body = '' then
    return null;
  end if;
  if title = '' then
    title := left(body, 120);
  end if;
  insert into public.line_room_calendar_search (
    room_id, line_message_id, event_title, event_description, starts_at, source
  ) values (
    p_room_id,
    nullif(btrim(p_line_message_id), ''),
    title,
    body,
    p_starts_at,
    coalesce(nullif(btrim(p_source), ''), 'line_talk')
  )
  on conflict (line_message_id) where line_message_id is not null
  do update set
    event_title = excluded.event_title,
    event_description = excluded.event_description,
    starts_at = excluded.starts_at
  returning id into row_id;
  return row_id;
end;
$$;

