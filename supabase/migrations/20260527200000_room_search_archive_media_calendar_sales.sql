-- ---------------------------------------------------------------------------
-- Purge extension
-- ---------------------------------------------------------------------------

create or replace function public.purge_line_room_messages_older_than(
  p_retention_days integer default 365
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  days int;
  cutoff timestamptz;
  search_deleted bigint := 0;
  calendar_deleted bigint := 0;
  calendar_talk_deleted bigint := 0;
  media_deleted bigint := 0;
  document_deleted bigint := 0;
  receipt_deleted bigint := 0;
  room_deleted bigint := 0;
  rec record;
  n bigint;
begin
  days := greatest(coalesce(p_retention_days, 365), 1);
  cutoff := now() - make_interval(days => days);

  delete from public.line_room_messages_search where created_at < cutoff;
  get diagnostics search_deleted = row_count;

  delete from public.line_room_calendar_events where coalesce(starts_at, created_at) < cutoff;
  get diagnostics calendar_deleted = row_count;

  delete from public.line_room_calendar_search where coalesce(starts_at, created_at) < cutoff;
  get diagnostics calendar_talk_deleted = row_count;

  delete from public.line_room_media_search where created_at < cutoff;
  get diagnostics media_deleted = row_count;

  delete from public.line_room_document_search where created_at < cutoff;
  get diagnostics document_deleted = row_count;

  delete from public.line_room_receipt_search where created_at < cutoff;
  get diagnostics receipt_deleted = row_count;

  for rec in select room_id, message_table from public.line_room_message_tables loop
    execute format('delete from public.%I where created_at < $1', rec.message_table) using cutoff;
    get diagnostics n = row_count;
    room_deleted := room_deleted + coalesce(n, 0);
  end loop;

  return jsonb_build_object(
    'retention_days', days,
    'cutoff', cutoff,
    'search_index_deleted', search_deleted,
    'calendar_deleted', calendar_deleted,
    'calendar_talk_deleted', calendar_talk_deleted,
    'media_deleted', media_deleted,
    'document_deleted', document_deleted,
    'receipt_search_deleted', receipt_deleted,
    'room_tables_deleted', room_deleted
  );
end;
$$;

