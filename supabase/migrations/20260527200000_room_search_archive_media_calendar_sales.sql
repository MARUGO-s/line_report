-- ---------------------------------------------------------------------------
-- Search: calendar (events + talk archive)
-- ---------------------------------------------------------------------------

create or replace function public.search_line_room_calendar_events(
  p_query text,
  p_room_id text default null,
  p_limit integer default 50,
  p_offset integer default 0
)
returns table (
  id bigint,
  room_id text,
  event_title text,
  event_description text,
  starts_at timestamptz,
  ends_at timestamptz,
  source text,
  external_event_id text,
  created_at timestamptz,
  total_count bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  q text;
  lim int;
  off int;
  since timestamptz := now() - interval '365 days';
  pattern text;
begin
  q := btrim(coalesce(p_query, ''));
  if length(q) < 1 then raise exception 'query required'; end if;
  lim := greatest(1, least(coalesce(p_limit, 50), 100));
  off := greatest(coalesce(p_offset, 0), 0);
  pattern := '%' || replace(replace(q, '\', '\\'), '%', '\%') || '%';

  if p_room_id is not null and btrim(p_room_id) <> '' and not public.is_valid_line_room_id(p_room_id) then
    raise exception 'invalid room_id: %', p_room_id;
  end if;

  return query
  with searchable_rooms as (
    select rs.room_id
    from public.room_summary_settings rs
    where rs.calendar_ai_auto_create_enabled = true
       or rs.calendar_silent_auto_register_enabled = true
  ),
  unified as (
    select
      e.id::bigint as id,
      e.room_id,
      e.event_title,
      e.event_description,
      e.starts_at,
      e.ends_at,
      e.source,
      e.external_event_id,
      e.created_at
    from public.line_room_calendar_events e
    inner join searchable_rooms sr on sr.room_id = e.room_id
    where coalesce(e.starts_at, e.created_at) >= since
      and (p_room_id is null or btrim(p_room_id) = '' or e.room_id = p_room_id)
      and (
        e.event_title ilike pattern escape '\'
        or e.event_description ilike pattern escape '\'
      )
    union all
    select
      c.id::bigint,
      c.room_id,
      c.event_title,
      c.event_description,
      c.starts_at,
      null::timestamptz as ends_at,
      c.source,
      null::text as external_event_id,
      c.created_at
    from public.line_room_calendar_search c
    inner join searchable_rooms sr on sr.room_id = c.room_id
    where coalesce(c.starts_at, c.created_at) >= since
      and (p_room_id is null or btrim(p_room_id) = '' or c.room_id = p_room_id)
      and (
        c.event_title ilike pattern escape '\'
        or c.event_description ilike pattern escape '\'
      )
  ),
  filtered as (
    select * from unified
  ),
  counted as (
    select count(*)::bigint as cnt from filtered
  )
  select
    f.id, f.room_id, f.event_title, f.event_description, f.starts_at, f.ends_at, f.source, f.external_event_id, f.created_at, c.cnt
  from filtered f
  cross join counted c
  order by coalesce(f.starts_at, f.created_at) desc nulls last
  limit lim offset off;
end;
$$;

