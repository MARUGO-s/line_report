-- ---------------------------------------------------------------------------
-- Search: media
-- ---------------------------------------------------------------------------

create or replace function public.search_line_room_media_search(
  p_query text,
  p_room_id text default null,
  p_limit integer default 50,
  p_offset integer default 0
)
returns table (
  id bigint,
  room_id text,
  line_message_id text,
  media_type text,
  original_file_name text,
  content_preview text,
  created_at timestamptz,
  total_count bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  q text;
  lim int;
  off int;
  since timestamptz := now() - interval '365 days';
  pattern text;
begin
  q := btrim(coalesce(p_query, ''));
  if length(q) < 1 then raise exception 'query required'; end if;
  lim := greatest(1, least(coalesce(p_limit, 50), 100));
  off := greatest(coalesce(p_offset, 0), 0);
  pattern := '%' || replace(replace(q, '\', '\\'), '%', '\%') || '%';

  return query
  with searchable_rooms as (
    select rs.room_id from public.room_summary_settings rs
    where rs.media_file_access_enabled = true
  ),
  filtered as (
    select m.*
    from public.line_room_media_search m
    inner join searchable_rooms sr on sr.room_id = m.room_id
    where m.created_at >= since
      and (p_room_id is null or btrim(p_room_id) = '' or m.room_id = p_room_id)
      and (
        m.content_preview ilike pattern escape '\'
        or coalesce(m.original_file_name, '') ilike pattern escape '\'
      )
  ),
  counted as (select count(*)::bigint as cnt from filtered)
  select f.id, f.room_id, f.line_message_id, f.media_type, f.original_file_name, f.content_preview, f.created_at, c.cnt
  from filtered f cross join counted c
  order by f.created_at desc limit lim offset off;
end;
$$;

