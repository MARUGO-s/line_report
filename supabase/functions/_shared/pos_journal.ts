export function buildPosJournalSummary(params: {
  storeKey: string;
  storeName: string;
  storeCode: string;
  month: string;
  days: PosJournalDay[];
  fileCount: number;
  generatedAt?: string;
  categoryOverrides?: Record<string, unknown>;
}): PosJournalSummary {
  const dayMap = new Map<string, PosJournalDay>();
  for (const day of params.days) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(day.business_date)) continue;
    dayMap.set(day.business_date, day);
  }
  const days = applyPosJournalCategoryOverrides(
    Array.from(dayMap.values()).sort((a, b) =>
      a.business_date.localeCompare(b.business_date)
    ),
    params.categoryOverrides ?? {},
  );
  const detailDays = days.map((day) => ({
    ...day,
    receipts: reconcilePosJournalDayDetail(day).receipts,
  }));
  const itemMap = new Map<
    string,
    {
      code: string;
      name: string;
      qty: number;
      amount: number;
      category?: PosJournalReceiptItem["category"];
    }
  >();
  const paymentBreakdown: Record<string, { count: number; amount: number }> =
    {};
  for (const day of detailDays) {
    for (const receipt of day.receipts || []) {
      for (const [method, amount] of Object.entries(
        resolvePosJournalReceiptPayments(receipt),
      )) {
        const payment = paymentBreakdown[method] ?? { count: 0, amount: 0 };
        payment.count += 1;
        payment.amount += amount;
        paymentBreakdown[method] = payment;
      }
      for (const item of receipt.items || []) {
        if (isPosJournalAdjustmentItem(item)) continue;
        const key = `${item.code}\u0000${item.name}`;
        const current = itemMap.get(key) ?? {
          code: item.code,
          name: item.name,
          qty: 0,
          amount: 0,
          category: item.category,
        };
        current.qty += Number(item.qty) || 0;
        current.amount += Number(item.amount) || 0;
        if (item.category) current.category = item.category;
        itemMap.set(key, current);
      }
    }
  }
  const gross = sumDays(days, "gross_sales");
  const paymentTotal = Object.values(paymentBreakdown).reduce(
    (sum, payment) => sum + payment.amount,
    0,
  );
  const guests = sumDays(days, "guests");
  let foodAmount = 0;
  let drinkAmount = 0;
  let roomAmount = 0;
  let otherAmount = 0;
  let chargeAmount = 0;
  for (const day of detailDays) {
    for (const receipt of day.receipts || []) {
      for (const item of receipt.items || []) {
        const amount = Number(item.amount) || 0;
        const primary = posJournalPrimaryCategory(item.category);
        if (primary === "フード") foodAmount += amount;
        else if (primary === "飲料") drinkAmount += amount;
        else if (primary === "室料") roomAmount += amount;
        else otherAmount += amount;
        if (item.isCharge) chargeAmount += amount;
      }
    }
  }
  return {
    meta: {
      store_key: params.storeKey,
      store_name: params.storeName,
      store_code: params.storeCode,
      month: params.month,
      file_count: params.fileCount,
      day_count: days.length,
      generated_at: params.generatedAt ?? new Date().toISOString(),
    },
    totals: {
      net_sales: sumDays(days, "net_sales"),
      tax: sumDays(days, "tax"),
      gross_sales: gross,
      groups: sumDays(days, "groups"),
      guests,
      avg_spend: guests ? Math.round(gross / guests) : 0,
      cash_amount: paymentBreakdown["現金"]?.amount || 0,
      credit_amount: paymentBreakdown["クレジット"]?.amount || 0,
      tabelog_amount: paymentBreakdown["食べログ"]?.amount || 0,
      ikyu_amount: paymentBreakdown["一休"]?.amount || 0,
      gurunavi_amount: paymentBreakdown["ぐるなび"]?.amount || 0,
      payment_total: paymentTotal,
      unattributed_payment_amount: Math.max(0, gross - paymentTotal),
      food_amount: foodAmount,
      drink_amount: drinkAmount,
      room_amount: roomAmount,
      other_amount: otherAmount,
      charge_amount: chargeAmount,
    },
    payment_breakdown: paymentBreakdown,
    item_ranking: Array.from(itemMap.values())
      .filter((item) => item.qty > 0 && item.amount >= 0)
      .sort((a, b) =>
        b.amount - a.amount || b.qty - a.qty ||
        a.name.localeCompare(b.name, "ja")
      ),
    days: detailDays,
  };
}
