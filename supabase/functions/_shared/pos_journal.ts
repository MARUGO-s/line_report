function paymentMethodRecord(
  day: PosJournalDay,
): Record<string, number> {
  const out: Record<string, number> = {};
  if (isRecord(day.payment_breakdown)) {
    for (const [rawLabel, rawBlock] of Object.entries(day.payment_breakdown)) {
      const label = normalizeSalePaymentLabel(rawLabel) || safeText(rawLabel, 30);
      const block = isRecord(rawBlock) ? rawBlock : {};
      const amount = safeNumber(block.amount);
      if (!label || !amount) continue;
      out[label] = (out[label] || 0) + amount;
    }
    if (Object.keys(out).length) return out;
  }
  const blocks: Array<[string, unknown]> = [
    ["現金", day.pay_cash],
    ["クレジット", day.pay_credit],
    ["食べログ", day.pay_tabelog],
    ["一休", day.pay_ikyu],
    ["ぐるなび", day.pay_gurunavi],
  ];
  for (const [label, raw] of blocks) {
    const block = isRecord(raw) ? raw : {};
    const amount = safeNumber(block.amount);
    if (amount) out[label] = amount;
  }
  return out;
}

function reconcilePosJournalReceipts(
  day: PosJournalDay,
): PosJournalReceipt[] {
  const receipts = removeVoidedPosJournalReceipts(
    Array.isArray(day.receipts) ? day.receipts : [],
  );
  if (!receipts.length) return []
  // VOIDの明示参照以外の近接・同内容heuristicは使わない。
  // 正常な別会計を誤って落とさず、合計不一致は上位の共通gateで日全体を除外する。
  return [...receipts].sort((a, b) =>
    safeText(a.time, 8).localeCompare(safeText(b.time, 8)) ||
    safeText(a.no, 30).localeCompare(safeText(b.no, 30))
  );
}

export type PosJournalDetailReconciliation = {
  /** 日計総売上・会計合計・各会計の商品合計が一致し、明細分析へ利用できる。 */
  detailComplete: boolean;
  reason:
    | "matched"
    | "gross_mismatch"
    | "item_mismatch"
    | "gross_and_item_mismatch";
  grossSales: number;
  rawReceiptCount: number;
  rawReceiptTotal: number;
  rawItemTotal: number;
  reconciledReceiptCount: number;
  reconciledReceiptTotal: number;
  reconciledItemTotal: number;
  itemMismatchReceiptCount: number;
  receipts: PosJournalReceipt[];
};

/**
 * 1営業日の会計明細を日計総売上へ照合する共通の安全境界。
 * 保存月報・商品インデックス・live商品検索・cohort比較は必ずこの結果だけを使う。
 * 一致できない元明細は監査用parsed_dataに残すが、確定明細としては返さない。
 */
export function reconcilePosJournalDayDetail(
  day: PosJournalDay,
): PosJournalDetailReconciliation {
  const rawReceipts = Array.isArray(day.receipts) ? day.receipts : [];
  const rawReceiptTotal = rawReceipts.reduce(
    (sum, receipt) => sum + safeNumber(receipt.total),
    0,
  );
  const rawItemTotal = rawReceipts.reduce(
    (sum, receipt) => sum + (Array.isArray(receipt.items)
      ? receipt.items.reduce(
        (itemSum, item) => itemSum + safeNumber(item.amount),
        0,
      )
      : 0),
    0,
  );
  const grossSales = safeNumber(day.gross_sales);
  const reconciled = reconcilePosJournalReceipts(day);
  const reconciledReceiptTotal = reconciled.reduce(
    (sum, receipt) => sum + safeNumber(receipt.total),
    0,
  );
  const reconciledItemTotal = reconciled.reduce(
    (sum, receipt) => sum + (Array.isArray(receipt.items)
      ? receipt.items.reduce(
        (itemSum, item) => itemSum + safeNumber(item.amount),
        0,
      )
      : 0),
    0,
  );
  const grossMatched = reconciledReceiptTotal === grossSales;
  const itemMismatchReceiptCount = reconciled.reduce((count, receipt) => {
    const items = Array.isArray(receipt.items) ? receipt.items : [];
    const itemTotal = items.reduce(
      (sum, item) => sum + safeNumber(item.amount),
      0,
    );
    return count + (items.length > 0 && itemTotal === safeNumber(receipt.total)
      ? 0
      : 1);
  }, 0);
  const itemsMatched = itemMismatchReceiptCount === 0;
  const detailComplete = grossMatched && itemsMatched;
  const reason = grossMatched
    ? (itemsMatched ? "matched" : "item_mismatch")
    : (itemsMatched ? "gross_mismatch" : "gross_and_item_mismatch");
  return {
    detailComplete,
    reason,
    grossSales,
    rawReceiptCount: rawReceipts.length,
    rawReceiptTotal,
    rawItemTotal,
    reconciledReceiptCount: detailComplete ? reconciled.length : 0,
    reconciledReceiptTotal,
    reconciledItemTotal,
    itemMismatchReceiptCount,
    receipts: detailComplete ? reconciled : [],
  };
}

function allocateDayPaymentsToSales(
  day: PosJournalDay,
  sales: JournalSavedReportSale[],
): void {
  if (!sales.length) return;
  const alreadyComplete = sales.every((sale) => {
    const byMethod = isRecord(sale.payments?.byMethod)
      ? sale.payments.byMethod
      : {};
    const allocated = Object.values(byMethod).reduce(
      (sum, amount) => sum + safeNumber(amount),
      0,
    );
    return Object.keys(byMethod).length > 0 && allocated === sale.total;
  });
  if (alreadyComplete) return;
  const targets = paymentMethodRecord(day);
  const targetEntries = Object.entries(targets).filter(([, amount]) =>
    amount !== 0
  );
  const targetTotal = targetEntries.reduce((sum, [, amount]) => sum + amount, 0);
  const salesTotal = sales.reduce((sum, sale) => sum + sale.total, 0);
  if (!targetEntries.length || targetTotal !== salesTotal) return;
  const remaining = new Map(targetEntries);
  for (const sale of sales) {
    let need = sale.total;
    const allocation: Record<string, number> = {};
    const order = [
      sale.method,
      ...targetEntries.map(([method]) => method).filter((method) =>
        method !== sale.method
      ),
    ];
    for (const method of order) {
      const available = remaining.get(method) || 0;
      if (!available || !need) continue;
      const amount = Math.min(available, need);
      allocation[method] = (allocation[method] || 0) + amount;
      remaining.set(method, available - amount);
      need -= amount;
    }
    if (need) allocation["その他"] = (allocation["その他"] || 0) + need;
    const methods = Object.keys(allocation).filter((method) =>
      allocation[method] !== 0
    );
    sale.method = methods.length === 1 ? methods[0] : "併用";
    sale.payments = {
      byMethod: allocation,
      total: sale.total,
      change: 0,
      details: methods.map((method) => ({
        label: method,
        method,
        amount: allocation[method],
      })),
    };
  }
}

function allocateDayTaxToSales(
  day: PosJournalDay,
  sales: JournalSavedReportSale[],
): void {
  if (!sales.length) return;
  const dayTax = safeNumber(day.tax);
  const total = sales.reduce((sum, sale) => sum + sale.total, 0);
  let assigned = 0;
  sales.forEach((sale, index) => {
    const tax = index === sales.length - 1
      ? dayTax - assigned
      : total
      ? Math.round(dayTax * sale.total / total)
      : 0;
    sale.tax = tax;
    assigned += tax;
  });
}

export function buildJournalSavedReportsFromPosDays(params: {
  storeKey: string;
  storeName: string;
  storeCode: string;
  month: string;
  days: PosJournalDay[];
  journalIds?: number[];
  categoryOverrides?: Record<string, unknown>;
  /** 店舗ごとのコード範囲。未指定ならコード内の既定値を使う。 */
  categoryRules?: PosJournalCategoryRules | null;
  createdAt?: string;
}): Array<{
  id: string;
  title: string;
  period: string;
  data: JournalSavedReportData;
}> {
  const month = String(params.month ?? "").trim();
  if (!/^\d{4}-(0[1-9]|1[0-2])$/.test(month)) return [];
  const dayMap = new Map<string, PosJournalDay>();
  for (const day of Array.isArray(params.days) ? params.days : []) {
    if (
      !/^\d{4}-\d{2}-\d{2}$/.test(day.business_date) ||
      day.business_date.slice(0, 7) !== month
    ) continue;
    dayMap.set(day.business_date, day);
  }
  const days = [...dayMap.values()].sort((a, b) =>
    a.business_date.localeCompare(b.business_date)
  );
  if (!days.length) return [];

  const overrides = isRecord(params.categoryOverrides)
    ? params.categoryOverrides
    : {};
  const sales: JournalSavedReportSale[] = [];
  const reportDays: PosJournalDay[] = [];
  const weatherByDate: Record<
    string,
    { weather: string; tempC: number | null }
  > = {};
  for (const day of days) {
    const daySaleStart = sales.length;
    const weather = safeText(day.weather, 30);
    const temperature = parsePosJournalTempC(day.temp_c, weather);
    if (weather || temperature != null) {
      weatherByDate[day.business_date] = {
        weather,
        tempC: temperature,
      };
    }
    const dayPayments = paymentMethodRecord(day);
    const detail = reconcilePosJournalDayDetail(day);
    const reconciledReceipts = detail.receipts;
    const targetDayTotal = detail.grossSales;
    // 日計と会計合計を一致させられない日は、誤った明細を確定値として保存しない。
    // 日計サマリー1件へ安全に退避し、元の生解析はpos_journal_filesに保持する。
    for (let index = 0; index < reconciledReceipts.length; index += 1) {
      const receipt = reconciledReceipts[index];
      const timeMatch = String(receipt.time ?? "").match(
        /^([01]?\d|2[0-3]):([0-5]\d)$/,
      );
      const hour = timeMatch ? Number(timeMatch[1]) : -1;
      const minute = timeMatch ? Number(timeMatch[2]) : -1;
      const hasAccountingTime = hour >= 0 && minute >= 0;
      const mealPeriod = hasAccountingTime
        ? ((hour * 60 + minute < 16 * 60) ? "ランチ" : "ディナー")
        : "";
      const items: JournalSavedReportSaleItem[] = (receipt.items || []).map(
        (item) => {
        const classification = classifyPosJournalReportItem(
          item.code,
          overrides,
          item.name,
          params.categoryRules ?? null,
        );
        return {
          code: safeText(item.code, 24),
          name: safeText(item.name, 120),
          qty: safeNumber(item.qty),
          amount: safeNumber(item.amount),
          ...classification,
        };
      }).filter((item) => item.name && (item.qty !== 0 || item.amount !== 0));
      const total = receipt.total == null
        ? items.reduce((sum, item) => sum + item.amount, 0)
        : safeNumber(receipt.total);
      const itemTotalBeforeAdjustment = items.reduce(
        (sum, item) => sum + item.amount,
        0,
      );
      const itemAdjustment = total - itemTotalBeforeAdjustment;
      if (itemAdjustment) {
        items.push({
          code: "__journal_adjustment__",
          name: "会計値調整",
          qty: 1,
          amount: itemAdjustment,
          category: "その他",
          isCharge: false,
          known: true,
          byCode: false,
          needsReview: false,
        });
      }
      const guests = receipt.guests == null ? 0 : safeNumber(receipt.guests);
      const byMethod = resolvePosJournalReceiptPayments(receipt);
      const methods = Object.keys(byMethod);
      const pay = methods.length === 1 ? methods[0] : "併用";
      const paymentAmount = Object.values(byMethod).reduce(
        (sum, amount) => sum + amount,
        0,
      );
      sales.push({
        no: safeText(receipt.no, 30) ||
          `${day.business_date.replace(/-/g, "")}-${index + 1}`,
        date: day.business_date,
        weekday: journalWeekday(day.business_date),
        hour,
        minute,
        hasAccountingTime,
        mealPeriod,
        time: hasAccountingTime
          ? `${String(hour).padStart(2, "0")}:${
            String(minute).padStart(2, "0")
          }`
          : "",
        total,
        tax: 0,
        points: 0,
        groups: 1,
        customers: guests,
        customerCountReliable: guests > 0,
        isSplitFragment: false,
        tableNo: safeText(receipt.table_no, 50),
        method: pay,
        change: 0,
        weather,
        tempC: Number.isFinite(temperature) ? temperature : null,
        payments: {
          byMethod,
          total: paymentAmount,
          change: 0,
          details: methods.map((method) => ({
            label: method,
            method,
            amount: byMethod[method],
          })),
        },
        items,
        itemTotal: items.reduce((sum, item) => sum + item.amount, 0),
      });
    }
    let daySales = sales.slice(daySaleStart);
    if (daySales.length) {
      // 日計サマリーを客数・組数・税の正本にする。割勘控え等で
      // レシート件数と組数が一致しない場合も、保存レポートは日計値へ合わせる。
      daySales.forEach((sale) => {
        sale.tax = 0;
        sale.groups = 0;
      });
      daySales[0].tax = safeNumber(day.tax);
      const targetGroups = Math.max(0, Math.round(safeNumber(day.groups)));
      for (
        let index = 0;
        index < Math.min(targetGroups, daySales.length);
        index += 1
      ) {
        daySales[index].groups = 1;
      }
      if (targetGroups > daySales.length) {
        daySales[0].groups += targetGroups - daySales.length;
      }
      const targetGuests = Math.max(0, Math.round(safeNumber(day.guests)));
      let guestDiff = targetGuests -
        daySales.reduce((sum, sale) => sum + sale.customers, 0);
      if (guestDiff > 0) {
        daySales[0].customers += guestDiff;
      } else if (guestDiff < 0) {
        let remaining = -guestDiff;
        for (const sale of daySales) {
          const take = Math.min(sale.customers, remaining);
          sale.customers -= take;
          remaining -= take;
          if (!remaining) break;
        }
      }
      daySales.forEach((sale) => {
        sale.customerCountReliable = sale.customers > 0;
      });
      allocateDayTaxToSales(day, daySales);
      allocateDayPaymentsToSales(day, daySales);
    }
    // 会計明細が無いプレースホルダでも、日計値は共有スナップショットに残す。
    if (!daySales.length && safeNumber(day.gross_sales) > 0) {
      const total = safeNumber(day.gross_sales);
      const paymentEntries = Object.entries(dayPayments);
      const pay = paymentEntries.length === 1
        ? paymentEntries[0][0]
        : paymentEntries.length > 1
        ? "併用"
        : "その他";
      sales.push({
        no: `summary-${day.business_date}`,
        date: day.business_date,
        weekday: journalWeekday(day.business_date),
        hour: -1,
        minute: -1,
        hasAccountingTime: false,
        mealPeriod: "",
        time: "",
        total,
        tax: safeNumber(day.tax),
        points: 0,
        groups: safeNumber(day.groups),
        customers: safeNumber(day.guests),
        customerCountReliable: safeNumber(day.guests) > 0,
        isSplitFragment: false,
        tableNo: "",
        method: pay,
        change: 0,
        weather,
        tempC: Number.isFinite(temperature) ? temperature : null,
        payments: {
          byMethod: paymentEntries.length ? dayPayments : { その他: total },
          total: paymentEntries.length
            ? paymentEntries.reduce((sum, [, value]) => sum + value, 0)
            : total,
          change: 0,
          details: paymentEntries.map(([label, amount]) => ({
            label,
            method: label,
            amount,
          })),
        },
        items: [],
        itemTotal: 0,
      });
    }
    daySales = sales.slice(daySaleStart);
    reportDays.push({
      business_date: day.business_date,
      source: safeText(day.source, 180) || "pos_journal_upload",
      net_sales: safeNumber(day.net_sales),
      tax: safeNumber(day.tax),
      gross_sales: safeNumber(day.gross_sales),
      groups: safeNumber(day.groups),
      guests: safeNumber(day.guests),
      avg_spend: safeNumber(day.avg_spend),
      pay_cash: isRecord(day.pay_cash)
        ? {
          count: safeNumber(day.pay_cash.count),
          amount: safeNumber(day.pay_cash.amount),
        }
        : { count: 0, amount: 0 },
      pay_credit: isRecord(day.pay_credit)
        ? {
          count: safeNumber(day.pay_credit.count),
          amount: safeNumber(day.pay_credit.amount),
        }
        : { count: 0, amount: 0 },
      pay_tabelog: isRecord(day.pay_tabelog)
        ? {
          count: safeNumber(day.pay_tabelog.count),
          amount: safeNumber(day.pay_tabelog.amount),
        }
        : { count: 0, amount: 0 },
      pay_ikyu: isRecord(day.pay_ikyu)
        ? {
          count: safeNumber(day.pay_ikyu.count),
          amount: safeNumber(day.pay_ikyu.amount),
        }
        : { count: 0, amount: 0 },
      pay_gurunavi: isRecord(day.pay_gurunavi)
        ? {
          count: safeNumber(day.pay_gurunavi.count),
          amount: safeNumber(day.pay_gurunavi.amount),
        }
        : { count: 0, amount: 0 },
      payment_breakdown: aggregatePosJournalReceiptPayments(
        daySales.map((sale) => ({
          no: sale.no,
          time: sale.time,
          pay: sale.method,
          total: sale.total,
          guests: sale.customers,
          payment_breakdown: sale.payments.byMethod,
          items: [],
        })),
      ),
      weather: safeText(day.weather, 30),
      temp_c: Number.isFinite(Number(day.temp_c)) ? Number(day.temp_c) : null,
      receipts: daySales.map((sale) => ({
        no: sale.no,
        time: sale.time,
        pay: sale.method,
        total: sale.total,
        guests: sale.customers,
        payment_breakdown: { ...sale.payments.byMethod },
        ...(sale.tableNo ? { table_no: sale.tableNo } : {}),
        items: sale.items.map((item) => ({
          code: item.code,
          name: item.name,
          unit: item.qty ? Math.round(item.amount / item.qty) : 0,
          qty: item.qty,
          amount: item.amount,
        })),
      })),
    });
  }
  sales.sort((a, b) =>
    a.date.localeCompare(b.date) ||
    a.time.localeCompare(b.time) ||
    a.no.localeCompare(b.no)
  );

  const total = days.reduce((sum, day) => sum + safeNumber(day.gross_sales), 0);
  const tax = days.reduce((sum, day) => sum + safeNumber(day.tax), 0);
  const totalCustomers = days.reduce(
    (sum, day) => sum + safeNumber(day.guests),
    0,
  );
  const totalGroups = days.reduce((sum, day) => sum + safeNumber(day.groups), 0);
  const categoryTotals: Record<PosJournalPrimaryCategory, number> = {
    "フード": 0,
    "飲料": 0,
    "室料": 0,
    "その他": 0,
  };
  // 画面の切替表示用。実際に割り当てられた粒度(細分類が付いていれば細分類)で
  // 積む。大分類の合計は上の categoryTotals が正で、こちらは内訳にすぎない。
  const categoryBreakdown: Record<string, number> = {};
  const mealCategoryTotals = {
    lunchTotal: 0,
    dinnerTotal: 0,
    lunchCustomers: 0,
    dinnerCustomers: 0,
    lunchFoodTotal: 0,
    lunchDrinkTotal: 0,
    dinnerFoodTotal: 0,
    dinnerDrinkTotal: 0,
  };
  let chargeTotal = 0;
  const productMap = new Map<
    string,
    { name: string; qty: number; amt: number; category: string }
  >();
  const weekdayMap = new Map<
    string,
    { totalSales: number; transactionCount: number; customerCount: number }
  >();
  const hourlyMap = new Map<
    number,
    { totalSales: number; count: number; customers: number }
  >();
  const dailyMap = new Map<
    string,
    { total: number; food: number; drink: number; groups: number; customers: number }
  >();
  for (const sale of sales) {
    const daily = dailyMap.get(sale.date) ??
      { total: 0, food: 0, drink: 0, groups: 0, customers: 0 };
    daily.total += sale.total;
    daily.groups += sale.groups;
    daily.customers += sale.customers;
    for (const item of sale.items) {
      // 細分類が入っていても、合計は必ず大分類へ寄せる。
      const primary = posJournalPrimaryCategory(item.category);
      categoryTotals[primary] += item.amount;
      const assigned = String(item.category ?? "").trim() || primary;
      categoryBreakdown[assigned] = (categoryBreakdown[assigned] ?? 0) +
        item.amount;
      if (primary === "フード") daily.food += item.amount;
      if (primary === "飲料") daily.drink += item.amount;
      if (item.isCharge) chargeTotal += item.amount;
      if (!isPosJournalAdjustmentItem(item)) {
        const product = productMap.get(item.name) ??
          { name: item.name, qty: 0, amt: 0, category: item.category };
        product.qty += item.qty;
        product.amt += item.amount;
        productMap.set(item.name, product);
      }
      if (sale.mealPeriod === "ランチ") {
        if (primary === "フード") {
          mealCategoryTotals.lunchFoodTotal += item.amount;
        } else if (primary === "飲料") {
          mealCategoryTotals.lunchDrinkTotal += item.amount;
        }
      } else if (sale.mealPeriod === "ディナー") {
        if (primary === "フード") {
          mealCategoryTotals.dinnerFoodTotal += item.amount;
        } else if (primary === "飲料") {
          mealCategoryTotals.dinnerDrinkTotal += item.amount;
        }
      }
    }
    dailyMap.set(sale.date, daily);
    if (sale.mealPeriod === "ランチ") {
      mealCategoryTotals.lunchTotal += sale.total;
      mealCategoryTotals.lunchCustomers += sale.customers;
    } else if (sale.mealPeriod === "ディナー") {
      mealCategoryTotals.dinnerTotal += sale.total;
      mealCategoryTotals.dinnerCustomers += sale.customers;
    }
    const weekday = sale.weekday || journalWeekday(sale.date);
    const weekdayRow = weekdayMap.get(weekday) ??
      { totalSales: 0, transactionCount: 0, customerCount: 0 };
    weekdayRow.totalSales += sale.total;
    weekdayRow.transactionCount += 1;
    weekdayRow.customerCount += sale.customers;
    weekdayMap.set(weekday, weekdayRow);
    if (sale.hour >= 0) {
      const hourly = hourlyMap.get(sale.hour) ??
        { totalSales: 0, count: 0, customers: 0 };
      hourly.totalSales += sale.total;
      hourly.count += 1;
      hourly.customers += sale.customers;
      hourlyMap.set(sale.hour, hourly);
    }
  }
  const categorized = Object.values(categoryTotals).reduce(
    (sum, value) => sum + value,
    0,
  );
  if (categorized !== total) {
    categoryTotals["その他"] += total - categorized;
  }
  const reportMonthLabel = `${Number(month.slice(0, 4))}年${
    Number(month.slice(5, 7))
  }月`;
  const createdAt = safeIsoTimestamp(params.createdAt);
  const journalIds = [...new Set(
    (params.journalIds || []).map(Number).filter((id) =>
      Number.isSafeInteger(id) && id > 0
    ),
  )];
  const topProducts = [...productMap.values()]
    .filter((item) => item.qty > 0 && item.amt >= 0)
    .sort((a, b) =>
      b.amt - a.amt || b.qty - a.qty || a.name.localeCompare(b.name, "ja")
    ).slice(0, 30);
  const weekdayBreakdown = [...weekdayMap.entries()]
    .map(([weekday, value]) => ({
      weekday,
      ...value,
      avgSpend: value.customerCount
        ? Math.round(value.totalSales / value.customerCount)
        : 0,
    }))
    .sort((a, b) =>
      POS_JOURNAL_REPORT_WEEKDAYS.indexOf(
        a.weekday as typeof POS_JOURNAL_REPORT_WEEKDAYS[number],
      ) -
      POS_JOURNAL_REPORT_WEEKDAYS.indexOf(
        b.weekday as typeof POS_JOURNAL_REPORT_WEEKDAYS[number],
      )
    );
  const hourlyBreakdown = [...hourlyMap.entries()].map(([hour, value]) => ({
    hour,
    ...value,
  })).sort((a, b) => a.hour - b.hour);
  const dailyBreakdown = [...dailyMap.entries()].map(([date, value]) => ({
    date,
    ...value,
  })).sort((a, b) => a.date.localeCompare(b.date));
  const period = dateRangeLabel(days);
  const baseData: Omit<JournalSavedReportData, "id" | "title"> = {
    period,
    createdAt,
    salesCount: sales.length,
    total,
    totalSales: total,
    categoryBreakdown,
    foodTotal: categoryTotals["フード"],
    drinkTotal: categoryTotals["飲料"],
    roomTotal: categoryTotals["室料"],
    otherTotal: categoryTotals["その他"],
    chargeTotal,
    ...mealCategoryTotals,
    totalCustomers,
    totalGroups,
    topProducts,
    weekdayBreakdown,
    hourlyBreakdown,
    dailyBreakdown,
    parserVersion: POS_JOURNAL_REPORT_PARSER_VERSION,
    verificationVersion: POS_JOURNAL_REPORT_VERIFICATION_VERSION,
    categoryVersion: POS_JOURNAL_REPORT_CATEGORY_VERSION,
    mealPeriodVersion: POS_JOURNAL_REPORT_MEAL_PERIOD_VERSION,
    sourceMonths: [month],
    journalIds,
    weatherByDate,
    posJournalDays: reportDays,
    sales,
    autoGeneratedFromPosJournal: true,
    autoGeneratedAt: createdAt,
  };
  return (["daily", "monthly"] as const).map((kind) => {
    const id = journalReportId(params.storeKey, month, kind);
    const title = kind === "daily"
      ? `日別売上レポート（${reportMonthLabel}）`
      : `月間売上レポート（${reportMonthLabel}）`;
    return {
      id,
      title,
      period,
      data: { ...baseData, id, title },
    };
  });
}

function sumDays(days: PosJournalDay[], key: string): number {
  return days.reduce((sum, day) => sum + (Number(day[key]) || 0), 0);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === "object" && !Array.isArray(value);
}

function safeNumber(value: unknown): number {
  const n = Number(value);
  return Number.isFinite(n) ? n : 0;
}

function safeText(value: unknown, maxLength = 180): string {
  return String(value ?? "").normalize("NFKC").replace(
    /[\u0000-\u001f\u007f]/g,
    " ",
  ).replace(/\s+/g, " ").trim().slice(0, maxLength);
}

/**
 * 会計内の支払方法別純額を検算して返す。
 * 旧解析版で「複数」へ潰れている場合は推測で配分せず、未捕捉として保持する。
 */
export function resolvePosJournalReceiptPayments(
  receipt: Pick<PosJournalReceipt, "pay" | "total" | "payment_breakdown">,
): Record<string, number> {
  const total = safeNumber(receipt.total);
  if (total <= 0) return {};
  const normalized: Record<string, number> = {};
  if (isRecord(receipt.payment_breakdown)) {
    for (const [rawLabel, rawAmount] of Object.entries(
      receipt.payment_breakdown,
    )) {
      const label = normalizeSalePaymentLabel(rawLabel) || safeText(rawLabel, 30);
      const amount = safeNumber(rawAmount);
      if (!label || amount <= 0) continue;
      normalized[label] = (normalized[label] || 0) + amount;
    }
  }
  const normalizedTotal = Object.values(normalized).reduce(
    (sum, amount) => sum + amount,
    0,
  );
  if (Object.keys(normalized).length && normalizedTotal === total) {
    return normalized;
  }
  const fallback = normalizeSalePaymentLabel(receipt.pay) ||
    safeText(receipt.pay, 30);
  if (
    fallback &&
    !/^(?:複数|併用|その他|不明)$/.test(fallback)
  ) {
    return { [fallback]: total };
  }
  return { "支払明細未捕捉": total };
}

function aggregatePosJournalReceiptPayments(
  receipts: readonly PosJournalReceipt[],
): Record<string, { count: number; amount: number }> {
  const output: Record<string, { count: number; amount: number }> = {};
  for (const receipt of receipts) {
    for (const [method, amount] of Object.entries(
      resolvePosJournalReceiptPayments(receipt),
    )) {
      const current = output[method] ?? { count: 0, amount: 0 };
      current.count += 1;
      current.amount += amount;
      output[method] = current;
    }
  }
  return output;
}

function paymentNameFromJournalReportSale(sale: JournalReportSaleLike): string {
  const byMethod = isRecord(sale.payments) && isRecord(sale.payments.byMethod)
    ? sale.payments.byMethod
    : {};
  const positive = Object.entries(byMethod)
    .filter(([, amount]) => safeNumber(amount) > 0)
    .sort((a, b) => safeNumber(b[1]) - safeNumber(a[1]));
  if (positive.length === 1) return safeText(positive[0][0], 30) || "不明";
  if (positive.length > 1) return "併用";
  return safeText(sale.method ?? sale.pay, 30) || "不明";
}

function journalReportReceipt(
  value: unknown,
  index: number,
): PosJournalReceipt | null {
  if (!isRecord(value)) return null;
  const sale = value as JournalReportSaleLike;
  const items = (Array.isArray(sale.items) ? sale.items : [])
    .map((item) => {
      if (!isRecord(item)) return null;
      const name = safeText(item.name, 120);
      if (!name) return null;
      const categoryText = safeText(item.category, 20);
      const category =
        (POS_JOURNAL_REPORT_CATEGORIES as readonly string[]).includes(
            categoryText,
          )
          ? categoryText as PosJournalReportCategory
          : undefined;
      return {
        code: safeText(item.code, 24),
        name,
        unit: safeNumber(item.unit) ||
          (safeNumber(item.qty) ? Math.round(safeNumber(item.amount) / safeNumber(item.qty)) : 0),
        qty: safeNumber(item.qty),
        amount: safeNumber(item.amount),
        ...(category ? { category } : {}),
        ...(item.isCharge === true ? { isCharge: true } : {}),
      };
    })
    .filter((item): item is PosJournalReceiptItem => item !== null);
  const rawTotal = Number(sale.total);
  const rawGuests = Number(sale.customers ?? sale.guests);
  const tableNo = safeText(sale.tableNo ?? sale.table_no, 50);
  const rawByMethod = isRecord(sale.payments) &&
      isRecord(sale.payments.byMethod)
    ? sale.payments.byMethod
    : isRecord(sale.payment_breakdown)
    ? sale.payment_breakdown
    : {};
  const paymentBreakdown: Record<string, number> = {};
  for (const [rawLabel, rawAmount] of Object.entries(rawByMethod)) {
    const label = normalizeSalePaymentLabel(rawLabel) || safeText(rawLabel, 30);
    const amount = safeNumber(rawAmount);
    if (label && amount > 0) {
      paymentBreakdown[label] = (paymentBreakdown[label] || 0) + amount;
    }
  }
  return {
    no: safeText(sale.no, 30) || `shared-${index + 1}`,
    time: safeText(sale.time, 8),
    pay: paymentNameFromJournalReportSale(sale),
    total: Number.isFinite(rawTotal) ? rawTotal : null,
    guests: Number.isFinite(rawGuests) ? rawGuests : null,
    ...(tableNo ? { table_no: tableNo } : {}),
    ...(Object.keys(paymentBreakdown).length
      ? { payment_breakdown: paymentBreakdown }
      : {}),
    items,
  };
}

/**
 * Journal Report の保存済みレポート（saved_reports.data）を
 * POS電子ジャーナル画面が扱う日次形式へ変換する。
 *
 * 原本LZHを複製せず、認証済み admin-api 内で共有参照するための変換。
 * 月間レポートは同じ月の全伝票を持つため、新しい保存行から日付ごとに
 * 初出の伝票だけを採用し、日別・月間の重複を二重計上しない。
 */
export function buildPosJournalDaysFromSavedReports(
  reports: Array<{ id?: unknown; data?: unknown; created_at?: unknown }>,
  month: string,
): PosJournalDay[] {
  if (!/^\d{4}-(0[1-9]|1[0-2])$/.test(month)) return [];
  const dayMap = new Map<string, PosJournalDay>();
  const rows = [...(Array.isArray(reports) ? reports : [])].sort((a, b) =>
    String(b.created_at ?? "").localeCompare(String(a.created_at ?? ""))
  );
  for (const row of rows) {
    const data = isRecord(row.data) ? row.data as JournalReportDataLike : {};
    const sharedDays = Array.isArray(data.posJournalDays)
      ? data.posJournalDays
      : [];
    for (const value of sharedDays) {
      if (!isRecord(value)) continue;
      const date = String(value.business_date ?? "").slice(0, 10);
      if (
        !/^\d{4}-\d{2}-\d{2}$/.test(date) ||
        date.slice(0, 7) !== month ||
        dayMap.has(date)
      ) {
        continue;
      }
      const receipts = (Array.isArray(value.receipts) ? value.receipts : [])
        .map(journalReportReceipt)
        .filter((receipt): receipt is PosJournalReceipt => receipt !== null);
      const paymentBlock = (
        key: string,
      ): { count: number; amount: number } => {
        const block = isRecord(value[key]) ? value[key] : {};
        return {
          count: safeNumber(block.count),
          amount: safeNumber(block.amount),
        };
      };
      dayMap.set(date, {
        business_date: date,
        source: safeText(value.source, 180) ||
          `saved_report:${safeText(row.id, 120) || "shared"}`,
        net_sales: safeNumber(value.net_sales),
        tax: safeNumber(value.tax),
        gross_sales: safeNumber(value.gross_sales),
        groups: safeNumber(value.groups),
        guests: safeNumber(value.guests),
        avg_spend: safeNumber(value.avg_spend),
        pay_cash: paymentBlock("pay_cash"),
        pay_credit: paymentBlock("pay_credit"),
        pay_tabelog: paymentBlock("pay_tabelog"),
        pay_ikyu: paymentBlock("pay_ikyu"),
        pay_gurunavi: paymentBlock("pay_gurunavi"),
        payment_breakdown: isRecord(value.payment_breakdown)
          ? value.payment_breakdown
          : aggregatePosJournalReceiptPayments(receipts),
        weather: safeText(value.weather, 30),
        temp_c: parsePosJournalTempC(
          value.temp_c ?? value.tempC,
          value.weather,
        ),
        receipts,
      });
    }
    const sales = Array.isArray(data.sales) ? data.sales : [];
    if (!sales.length) continue;
    const byDate = new Map<string, JournalReportSaleLike[]>();
    for (const sale of sales) {
      if (!isRecord(sale)) continue;
      const date = String(sale.date ?? "").slice(0, 10);
      if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || date.slice(0, 7) !== month) {
        continue;
      }
      const list = byDate.get(date) ?? [];
      list.push(sale as JournalReportSaleLike);
      byDate.set(date, list);
    }
    const weatherByDate = isRecord(data.weatherByDate) ? data.weatherByDate : {};
    for (const [date, daySales] of byDate) {
      if (dayMap.has(date)) continue;
      const receipts = daySales.map(journalReportReceipt).filter(
        (receipt): receipt is PosJournalReceipt => receipt !== null,
      );
      const gross = daySales.reduce((sum, sale) => sum + safeNumber(sale.total), 0);
      const tax = daySales.reduce((sum, sale) => sum + safeNumber(sale.tax), 0);
      const guests = daySales.reduce(
        (sum, sale) => sum + safeNumber(sale.customers ?? sale.guests),
        0,
      );
      const groups = daySales.reduce(
        (sum, sale) =>
          sum +
          (sale.groups != null
            ? safeNumber(sale.groups)
            : sale.isSplitFragment === true
            ? 0
            : 1),
        0,
      );
      const paymentTotals = new Map<string, { count: number; amount: number }>();
      for (const sale of daySales) {
        const payments = isRecord(sale.payments) && isRecord(sale.payments.byMethod)
          ? sale.payments.byMethod
          : null;
        if (payments) {
          for (const [name, value] of Object.entries(payments)) {
            const amount = safeNumber(value);
            if (!amount) continue;
            const current = paymentTotals.get(name) ?? { count: 0, amount: 0 };
            current.count += 1;
            current.amount += amount;
            paymentTotals.set(name, current);
          }
        } else {
          const name = paymentNameFromJournalReportSale(sale);
          const current = paymentTotals.get(name) ?? { count: 0, amount: 0 };
          current.count += 1;
          current.amount += safeNumber(sale.total);
          paymentTotals.set(name, current);
        }
      }
      const weatherRow = isRecord(weatherByDate[date]) ? weatherByDate[date] : {};
      const saleWeather = daySales.find((sale) => safeText(sale.weather, 30));
      const saleTemp = daySales.find((sale) =>
        parsePosJournalTempC(sale.tempC ?? sale.temp_c, sale.weather) != null
      );
      const day: PosJournalDay = {
        business_date: date,
        source: `saved_report:${safeText(row.id, 120) || "shared"}`,
        net_sales: Math.max(0, gross - tax),
        tax,
        gross_sales: gross,
        groups,
        guests,
        avg_spend: guests ? Math.round(gross / guests) : 0,
        pay_cash: paymentTotals.get("現金") ?? { count: 0, amount: 0 },
        pay_credit: paymentTotals.get("クレジット") ?? { count: 0, amount: 0 },
        pay_tabelog: paymentTotals.get("食べログ") ?? { count: 0, amount: 0 },
        pay_ikyu: paymentTotals.get("一休") ?? { count: 0, amount: 0 },
        pay_gurunavi: paymentTotals.get("ぐるなび") ?? { count: 0, amount: 0 },
        payment_breakdown: Object.fromEntries(paymentTotals),
        weather: safeText(weatherRow.weather ?? saleWeather?.weather, 30),
        temp_c: parsePosJournalTempC(
          weatherRow.tempC ?? weatherRow.temp_c,
          weatherRow.weather ?? saleWeather?.weather,
        ) ?? parsePosJournalTempC(
          saleTemp?.tempC ?? saleTemp?.temp_c,
          saleTemp?.weather,
        ),
        receipts,
      };
      dayMap.set(date, day);
    }
  }
  return [...dayMap.values()].sort((a, b) =>
    a.business_date.localeCompare(b.business_date)
  );
}

export function pickBestJournalSavedReportDays(
  reports: Array<{ id?: unknown; data?: unknown; created_at?: unknown }>,
  month: string,
): PosJournalDay[] {
  const reportList = Array.isArray(reports) ? reports : [];
  const candidates = reportList.map((report, index) => {
    const days = buildPosJournalDaysFromSavedReports([report], month);
    return {
      days,
      dayCount: days.length,
      gross: days.reduce((sum, day) => sum + safeNumber(day.gross_sales), 0),
      receipts: days.reduce(
        (sum, day) => sum + (Array.isArray(day.receipts) ? day.receipts.length : 0),
        0,
      ),
      index,
    };
  });
  const bestIndividual = candidates
    .filter((candidate) => candidate.dayCount > 0)
    .sort((a, b) =>
      b.dayCount - a.dayCount ||
      b.gross - a.gross ||
      b.receipts - a.receipts ||
      a.index - b.index
    )[0];
  // 月間レポートが無く、日別レポートが複数行に分かれている旧データも
  // 営業日単位で統合する。ただし既存の最広レポートと同じ日数なら、
  // 新しい部分断片で完全月の同一日を上書きしない。
  const mergedDays = buildPosJournalDaysFromSavedReports(reportList, month);
  if (mergedDays.length > (bestIndividual?.dayCount ?? 0)) {
    candidates.push({
      days: mergedDays,
      dayCount: mergedDays.length,
      gross: mergedDays.reduce(
        (sum, day) => sum + safeNumber(day.gross_sales),
        0,
      ),
      receipts: mergedDays.reduce(
        (sum, day) =>
          sum + (Array.isArray(day.receipts) ? day.receipts.length : 0),
        0,
      ),
      index: reportList.length,
    });
  }
  return candidates.filter((candidate) => candidate.dayCount > 0).sort((a, b) =>
    b.dayCount - a.dayCount ||
    b.gross - a.gross ||
    b.receipts - a.receipts ||
    a.index - b.index
  )[0]?.days ?? [];
}

/** primary（LZH原本）を同一営業日の正本として fallback（保存レポート）へ重ねる。 */
export function mergePosJournalDaysPreferPrimary(
  primary: PosJournalDay[],
  fallback: PosJournalDay[],
): PosJournalDay[] {
  const byDate = new Map<string, PosJournalDay>();
  for (const day of Array.isArray(fallback) ? fallback : []) {
    if (/^\d{4}-\d{2}-\d{2}$/.test(day.business_date)) {
      byDate.set(day.business_date, day);
    }
  }
  for (const day of Array.isArray(primary) ? primary : []) {
    if (/^\d{4}-\d{2}-\d{2}$/.test(day.business_date)) {
      const existing = byDate.get(day.business_date);
      const detail = reconcilePosJournalDayDetail(day);
      // 古いサーバー解析で取消行を落として商品明細だけ過大な場合、
      // 日計・決済・天候は原本を正とし、明細だけ既存保存レポートを維持する。
      byDate.set(
        day.business_date,
        existing && !detail.detailComplete
          ? { ...existing, ...day, receipts: existing.receipts }
          : { ...day, receipts: detail.receipts },
      );
    }
  }
  return [...byDate.values()].sort((a, b) =>
    a.business_date.localeCompare(b.business_date)
  );
}

