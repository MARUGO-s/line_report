export function posJournalWeatherText(value: unknown): string {
  return String(value ?? "").trim();
}

/** 未入力・空文字・天候なしの 0℃ は欠落とみなす（Number(null) === 0 の化け防止）。 */
export function parsePosJournalTempC(
  value: unknown,
  weather: unknown = "",
): number | null {
  if (value == null) return null;
  if (typeof value === "string" && value.trim() === "") return null;
  const n = Number(value);
  if (!Number.isFinite(n)) return null;
  if (n === 0 && !posJournalWeatherText(weather)) return null;
  return n;
}

export function posJournalDayNeedsWeather(day: {
  weather?: unknown;
  temp_c?: unknown;
  tempC?: unknown;
}): boolean {
  const weather = posJournalWeatherText(day?.weather);
  const temp = parsePosJournalTempC(day?.temp_c ?? day?.tempC, weather);
  return !weather || temp == null;
}

export function posJournalWeatherLabelFromCache(
  day: PosJournalWeatherCacheDay | null | undefined,
): string {
  if (!day) return "";
  const code = day.code == null ? NaN : Number(day.code);
  if (Number.isFinite(code)) {
    if (code === 0 || code === 1 || code === 2) return "晴れ";
    if (code === 3) return "曇り";
    if (code >= 45 && code <= 48) return "霧";
    if (code >= 51 && code <= 57) return "霧雨";
    if (code >= 61 && code <= 67) return code >= 65 ? "大雨" : "雨";
    if (code >= 71 && code <= 77) return "雪";
    if (code >= 80 && code <= 82) return "にわか雨";
    if (code >= 85 && code <= 86) return "雪";
    if (code >= 95) return "雷雨";
  }
  if (day.rain != null && Number(day.rain) > 0.5) return "雨";
  if (day.temp != null && Number.isFinite(Number(day.temp))) return "晴れ";
  return "";
}

export function applyCachedWeatherToPosJournalDays(
  days: PosJournalDay[],
  weatherByDate: Record<string, PosJournalWeatherCacheDay>,
): PosJournalDay[] {
  const cache = weatherByDate && typeof weatherByDate === "object"
    ? weatherByDate
    : {};
  return (Array.isArray(days) ? days : []).map((day) => {
    const weather = posJournalWeatherText(day.weather);
    const temp = parsePosJournalTempC(day.temp_c ?? day.tempC, weather);
    if (weather && temp != null) return day;
    const cached = cache[day.business_date];
    const filledWeather = weather || posJournalWeatherLabelFromCache(cached);
    const filledTemp = temp != null
      ? temp
      : (cached && cached.temp != null && Number.isFinite(Number(cached.temp))
        ? Math.round(Number(cached.temp))
        : null);
    if (filledWeather === weather && filledTemp === temp) {
      return { ...day, weather, temp_c: temp };
    }
    return { ...day, weather: filledWeather, temp_c: filledTemp };
  });
}
const FULLWIDTH_MAP: Readonly<Record<string, string>> = {
  "０": "0",
  "１": "1",
  "２": "2",
  "３": "3",
  "４": "4",
  "５": "5",
  "６": "6",
  "７": "7",
  "８": "8",
  "９": "9",
  "，": ",",
  "．": ".",
  "％": "%",
  "／": "/",
  "－": "-",
};

function normalizeWide(value: string): string {
  return String(value || "").replace(
    /[０-９，．％／－]/g,
    (char) => FULLWIDTH_MAP[char] ?? char,
  );
}

function normalizedCodeNumber(value: unknown): number | null {
  const digits = String(value ?? "").normalize("NFKC").replace(/\D/g, "");
  if (!digits) return null;
  const n = Number(digits);
  return Number.isFinite(n) ? n : null;
}

function numberInRanges(
  value: number | null,
  ranges: ReadonlyArray<[number, number]>,
): boolean {
  return value != null &&
    ranges.some(([from, to]) => value >= from && value <= to);
}

/**
 * 店舗ごとのコード範囲。画面の入力欄と同じテキスト仕様を解釈した結果を持つ。
 * 行の無い店舗では null を渡し、コード内の既定値へフォールバックする。
 */
export type PosJournalCategoryRules = {
  food: ReadonlyArray<CodeSpec>;
  drink: ReadonlyArray<CodeSpec>;
  room: ReadonlyArray<CodeSpec>;
  charge: ReadonlyArray<CodeSpec>;
};

type CodeSpec =
  | { kind: "range"; start: number; end: number }
  | { kind: "code"; digits: string; number: number };

/**
 * '0100-0199, 0250' 形式を解釈する。
 * 画面側 parseCategorySpecs と同じ規則にすること。ここがずれると、
 * 同じ設定でも画面と保存レポートで分類が食い違う。
 */
export function parsePosJournalCodeSpecs(spec: unknown): CodeSpec[] {
  return String(spec ?? "")
    .split(/[\s,、;；]+/)
    .map((token) => token.trim())
    .filter(Boolean)
    .map((token): CodeSpec | null => {
      const range = token.match(/^(\d+)\s*[-〜～]\s*(\d+)$/);
      if (range) {
        const start = Number(range[1]);
        const end = Number(range[2]);
        if (!Number.isFinite(start) || !Number.isFinite(end)) return null;
        return {
          kind: "range",
          start: Math.min(start, end),
          end: Math.max(start, end),
        };
      }
      const digits = String(token).normalize("NFKC").replace(/[^0-9]/g, "");
      if (!digits) return null;
      return { kind: "code", digits, number: Number(digits) };
    })
    .filter((spec): spec is CodeSpec => spec !== null);
}

/** DBの1行から解釈済みの範囲を作る。全欄が空なら null(=既定値を使う)。 */
export function buildPosJournalCategoryRules(
  row: Record<string, unknown> | null | undefined,
): PosJournalCategoryRules | null {
  if (!isRecord(row)) return null;
  const rules: PosJournalCategoryRules = {
    food: parsePosJournalCodeSpecs(row.food_codes),
    drink: parsePosJournalCodeSpecs(row.drink_codes),
    room: parsePosJournalCodeSpecs(row.room_codes),
    charge: parsePosJournalCodeSpecs(row.charge_codes),
  };
  const configured = rules.food.length + rules.drink.length + rules.room.length +
    rules.charge.length;
  return configured ? rules : null;
}

function codeSpecMatches(
  specs: ReadonlyArray<CodeSpec>,
  digits: string,
  number: number | null,
): boolean {
  return specs.some((spec) =>
    spec.kind === "code"
      ? (spec.digits === digits || (number != null && spec.number === number))
      : (number != null && number >= spec.start && number <= spec.end)
  );
}

export function classifyPosJournalReportItem(
  code: unknown,
  overrides: Record<string, unknown> = {},
  name: unknown = "",
  /** 店舗ごとのコード範囲。null なら従来どおりコード内の既定値を使う。 */
  rules: PosJournalCategoryRules | null = null,
): {
  category: PosJournalReportCategory;
  isCharge: boolean;
  known: boolean;
  byCode: boolean;
  byOverride: boolean;
  needsReview: boolean;
} {
  const codeText = String(code ?? "").normalize("NFKC").trim();
  const nameText = String(name ?? "").normalize("NFKC").replace(/\s+/g, " ")
    .trim();
  const overrideKey = `${codeText}|${nameText}`;
  const override = String(overrides[overrideKey] ?? "").trim();
  const number = normalizedCodeNumber(codeText);
  const digits = codeText.replace(/[^0-9]/g, "");
  // 店舗設定があればそちらを正とする。無ければ従来の定数。
  const isCharge = rules
    ? codeSpecMatches(rules.charge, digits, number)
    : (number != null && POS_JOURNAL_CHARGE_CODES.has(number));
  if (
    (POS_JOURNAL_REPORT_CATEGORIES as readonly string[]).includes(override)
  ) {
    return {
      category: override as PosJournalReportCategory,
      isCharge,
      known: true,
      byCode: false,
      byOverride: true,
      needsReview: false,
    };
  }
  const matchesFood = rules
    ? codeSpecMatches(rules.food, digits, number)
    : numberInRanges(number, POS_JOURNAL_FOOD_RANGES);
  const matchesDrink = rules
    ? codeSpecMatches(rules.drink, digits, number)
    : numberInRanges(number, POS_JOURNAL_DRINK_RANGES);
  const matchesRoom = rules
    ? codeSpecMatches(rules.room, digits, number)
    : (number != null && POS_JOURNAL_ROOM_CODES.has(number));
  // チャージだけに当たった商品はフードの内数として扱う（画面側と同じ規則）。
  if (matchesFood || isCharge) {
    return {
      category: "フード",
      isCharge,
      known: true,
      byCode: true,
      byOverride: false,
      needsReview: false,
    };
  }
  if (matchesDrink) {
    return {
      category: "飲料",
      isCharge: false,
      known: true,
      byCode: true,
      byOverride: false,
      needsReview: false,
    };
  }
  if (matchesRoom) {
    return {
      category: "室料",
      isCharge: false,
      known: true,
      byCode: true,
      byOverride: false,
      needsReview: false,
    };
  }
  return {
    category: "その他",
    isCharge: false,
    known: true,
    byCode: false,
    byOverride: false,
    needsReview: true,
  };
}

export function applyPosJournalCategoryOverrides(
  days: PosJournalDay[],
  overrides: Record<string, unknown> = {},
  rules: PosJournalCategoryRules | null = null,
): PosJournalDay[] {
  return (Array.isArray(days) ? days : []).map((day) => ({
    ...day,
    receipts: (Array.isArray(day.receipts) ? day.receipts : []).map(
      (receipt) => ({
        ...receipt,
        items: (Array.isArray(receipt.items) ? receipt.items : []).map(
          (item) => {
            const classified = classifyPosJournalReportItem(
              item.code,
              overrides,
              item.name,
              rules,
            );
            const existing = String(item.category ?? "").trim();
            const keepExisting =
              !classified.byOverride &&
              (POS_JOURNAL_REPORT_CATEGORIES as readonly string[]).includes(
                existing,
              );
            return {
              ...item,
              category: keepExisting
                ? existing as PosJournalReportCategory
                : classified.category,
              isCharge: classified.isCharge || item.isCharge === true,
            };
          },
        ),
      }),
    ),
  }));
}

function stripEscPos(raw: Uint8Array): string {
  const output: number[] = [];
  for (let index = 0; index < raw.length;) {
    const byte = raw[index];
    if (byte === 0x1b || byte === 0x1c) {
      index += 3;
      continue;
    }
    output.push(byte);
    index += 1;
  }
  return new TextDecoder("shift-jis", { fatal: false }).decode(
    Uint8Array.from(output),
  );
}

function amount(value: string): number | null {
  const match = normalizeWide(value).match(/\\\s*([\d,]+)/);
  return match ? Number(match[1].replace(/,/g, "")) : null;
}

function firstInt(value: string, unit: string): number | null {
  const match = normalizeWide(value).match(new RegExp(`([\\d,]+)\\s*${unit}`));
  return match ? Number(match[1].replace(/,/g, "")) : null;
}

type JournalRecord = {
  no: string;
  y: number;
  mo: number;
  d: number;
  wd: string;
  hh: number;
  mi: number;
  lines: string[];
};

function splitRecords(text: string): JournalRecord[] {
  const records: JournalRecord[] = [];
  let current: JournalRecord | null = null;
  for (const line of text.split(/\r?\n|\r/g)) {
    const match = line.match(HEADER_RE);
    if (match) {
      if (current) records.push(current);
      current = {
        no: match[2],
        y: Number(match[3]),
        mo: Number(match[4]),
        d: Number(match[5]),
        wd: match[6],
        hh: Number(match[7]),
        mi: Number(match[8]),
        lines: [],
      };
    } else if (current) current.lines.push(line);
  }
  if (current) records.push(current);
  return records;
}

function valueNear(lines: string[], index: number, look = 2): number | null {
  for (
    let cursor = index;
    cursor < Math.min(index + look + 1, lines.length);
    cursor += 1
  ) {
    const value = amount(lines[cursor]);
    if (value != null) return value;
  }
  return null;
}

function parseSettlement(record: JournalRecord): Record<string, unknown> {
  const lines = record.lines;
  const output: Record<string, unknown> = {};
  for (const line of lines) {
    const match = normalizeWide(line).match(
      /営業日付[：:]\s*(\d{4})年\s*(\d+)月\s*(\d+)日/,
    );
    if (match) {
      output.business_date = `${Number(match[1]).toString().padStart(4, "0")}-${
        Number(match[2]).toString().padStart(2, "0")
      }-${Number(match[3]).toString().padStart(2, "0")}`;
      break;
    }
  }
  const amountLabels: Readonly<Record<string, string>> = {
    net_sales: "純 売 上",
    tax: "消 費 税",
    gross_sales: "総 売 上",
    avg_spend: "客単価",
    discount_total: "★割引合計",
    pay_total: "★支払合計",
    tax_out: " 外税",
    tax_in: " 内税",
  };
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    for (const [key, label] of Object.entries(amountLabels)) {
      if (!(key in output) && line.includes(label)) {
        const value = amount(line) ?? valueNear(lines, index, 1);
        if (value != null) output[key] = value;
      }
    }
    if (line.includes("会計組数・客数")) {
      for (
        let cursor = index;
        cursor < Math.min(index + 3, lines.length);
        cursor += 1
      ) {
        const groups = firstInt(lines[cursor], "組");
        const guests = firstInt(lines[cursor], "名");
        if (groups != null) output.groups = groups;
        if (guests != null) output.guests = guests;
      }
    }
    if (line.includes("店内飲食売上")) {
      for (
        let cursor = index;
        cursor < Math.min(index + 3, lines.length);
        cursor += 1
      ) {
        const items = firstInt(lines[cursor], "点");
        const sales = amount(lines[cursor]);
        if (items != null) output.dinein_items = items;
        if (sales != null) output.dinein_sales = sales;
      }
    }
  }
  const paymentBlock = (label: string): { count: number; amount: number } => {
    for (let index = 0; index < lines.length; index += 1) {
      if (!lines[index].includes(label)) continue;
      let count = 0;
      let value = 0;
      for (
        let cursor = index;
        cursor < Math.min(index + 3, lines.length);
        cursor += 1
      ) {
        const foundCount = firstInt(lines[cursor], "回");
        const foundAmount = amount(lines[cursor]);
        if (foundCount != null) count = foundCount;
        if (foundAmount != null) value = foundAmount;
      }
      return { count, amount: value };
    }
    return { count: 0, amount: 0 };
  };
  output.pay_cash = paymentBlock("現計");
  output.pay_credit = paymentBlock("クレジット計");
  output.pay_tabelog = paymentBlock("食べログ");
  output.pay_ikyu = paymentBlock("一休");
  output.pay_gurunavi = paymentBlock("ぐるなび");
  return output;
}

function parseWeather(record: JournalRecord): Record<string, unknown> {
  const output: Record<string, unknown> = {};
  for (const line of record.lines) {
    const weather = line.match(/天候\s*([^\s　]+)/);
    if (weather && !line.includes("入力") && weather[1] !== "入力") {
      output.weather = weather[1].trim();
    }
    const temperature = normalizeWide(line).match(/気温\s*(\d+)/);
    if (temperature) output.temp_c = Number(temperature[1]);
  }
  return output;
}

function normalizeSalePaymentLabel(value: unknown): string {
  const label = String(value ?? "").normalize("NFKC").trim();
  if (!label) return "";
  if (/^現計/.test(label)) return "現金";
  if (/クレジット/.test(label)) return "クレジット";
  if (/食べログ/.test(label)) return "食べログ";
  if (/一休/.test(label)) return "一休";
  if (/ぐるなび/.test(label)) return "ぐるなび";
  if (/QR\s*コード/i.test(label)) return "QRコード";
  if (/電子\s*マネ/.test(label)) return "電子マネー";
  if (/東京\s*ドーム\s*利/.test(label)) return "東京ドーム利用券";
  if (/ドーム\s*シティ\s*食事/.test(label)) return "ドームシティ食事券";
  if (/FOOD\s*STADIUM/i.test(label)) return "FOODSTADIUM利用券";
  if (/TD\s*ポイント/i.test(label)) return "TDポイントチケット";
  if (/^掛(?:計|支払|売)/.test(label)) return "掛売";
  return label.replace(/[\s　]+/g, " ").replace(/計$/, "").slice(0, 30);
}

function parseSale(record: JournalRecord): PosJournalReceipt | null {
  const text = record.lines.join("\n");
  const normalizedText = normalizeWide(text).normalize("NFKC");
  if (/オーダーキャンセル|未会計オーダー取消|取引中止/.test(normalizedText)) {
    return null;
  }
  const paymentBreakdown: Record<string, number> = {};
  for (const line of record.lines) {
    // 実POSは店舗ごとの任意支払区分（QR・電子マネー・商品券等）を
    // 「計N 支払名 \\金額」で出す。既知5種だけに限定すると会計全体が欠落する。
    const paymentLine = normalizeWide(line).normalize("NFKC").match(
      /^\s*計\d+\s+(.+?)\s+[\\¥￥]\s*(-?[\d,]+)\s*$/,
    );
    if (!paymentLine) continue;
    const method = normalizeSalePaymentLabel(paymentLine[1]);
    const paymentAmount = Number(paymentLine[2].replace(/,/g, ""));
    if (method && Number.isFinite(paymentAmount)) {
      paymentBreakdown[method] =
        (paymentBreakdown[method] || 0) + paymentAmount;
    }
  }
  const paymentMethods = Object.keys(paymentBreakdown).filter((method) =>
    paymentBreakdown[method] !== 0
  );
  const detectedPay = paymentMethods.length === 1
    ? paymentMethods[0]
    : (paymentMethods.length > 1 ? "複数" : "");
  const items: PosJournalReceiptItem[] = [];
  for (let index = 0; index < record.lines.length; index += 1) {
    const item = record.lines[index].match(ITEM_CODE_RE);
    if (!item || index + 1 >= record.lines.length) continue;
    const price = normalizeWide(record.lines[index + 1]).match(ITEM_PRICE_RE);
    if (!price) continue;
    items.push({
      code: item[1],
      name: item[2].trim(),
      unit: Number(price[1].replace(/,/g, "")),
      qty: Number(price[2].replace(/,/g, "")),
      amount: Number(price[3].replace(/,/g, "")),
    });
    index += 1;
  }
  for (let index = 0; index < record.lines.length; index += 1) {
    const label = normalizeWide(record.lines[index]).normalize("NFKC").trim();
    if (label !== "割引" && label !== "値引") continue;
    for (let next = index + 1; next < record.lines.length; next += 1) {
      const adjustmentLine = normalizeWide(record.lines[next]).normalize("NFKC")
        .trim();
      if (!adjustmentLine) continue;
      const adjustment = adjustmentLine.match(/[\\¥]?\s*(-?[\d,]+)\s*$/);
      if (adjustment) {
        const adjustmentAmount = Number(adjustment[1].replace(/,/g, ""));
        if (Number.isFinite(adjustmentAmount) && adjustmentAmount !== 0) {
          items.push({
            code: POS_JOURNAL_ADJUSTMENT_ITEM_CODE,
            name: label,
            unit: adjustmentAmount,
            qty: 1,
            amount: adjustmentAmount,
            category: "その他",
            isCharge: false,
          });
        }
      }
      break;
    }
  }
  if (!items.length) return null;
  let total: number | null = null;
  let guests: number | null = null;
  let tableNo = "";
  let change = 0;
  for (const line of record.lines) {
    const normalized = String(line || "").normalize("NFKC");
    if (/合\s*計\s/.test(line)) total = amount(line) ?? total;
    if (/お[\s　]*釣/.test(normalized)) change = amount(line) ?? change;
    guests = firstInt(line, "名") ?? guests;
    const table = normalized.match(
      /(?:伝票\s*No\.?\s*[^\s]+\s+)?テーブル\s*No\.?\s*([^\s]+)/,
    );
    if (table) {
      const tbl = String(table[1] || "").trim();
      if (tbl && !/^保留/.test(tbl) && tbl !== ".") tableNo = tbl;
    }
  }
  if (!detectedPay && total == null) return null;
  const pay = detectedPay || "支払情報なし";
  if (change && paymentBreakdown["現金"] != null) {
    paymentBreakdown["現金"] -= change;
  }
  if (!Object.keys(paymentBreakdown).length && total != null && total > 0) {
    paymentBreakdown["支払情報なし"] = total;
  }
  const voidRef = text.normalize("NFKC").match(
    /★\s*VOID\s+No\.?\s*(\d+)/i,
  )?.[1] ?? "";
  return {
    no: record.no,
    time: `${String(record.hh).padStart(2, "0")}:${
      String(record.mi).padStart(2, "0")
    }`,
    pay,
    total,
    guests,
    ...(tableNo ? { table_no: tableNo } : {}),
    ...(voidRef ? { void_ref: voidRef } : {}),
    payment_breakdown: paymentBreakdown,
    items,
  };
}

/** 取引変更のVOID控え自身と、参照された直前の元会計だけを除外する。 */
export function removeVoidedPosJournalReceipts(
  receipts: readonly PosJournalReceipt[],
): PosJournalReceipt[] {
  const list = Array.isArray(receipts) ? [...receipts] : [];
  const active = list.map(() => true);
  for (let index = 0; index < list.length; index += 1) {
    const voidRef = safeText(list[index]?.void_ref, 30);
    if (!voidRef) continue;
    active[index] = false;
    for (let prior = index - 1; prior >= 0; prior -= 1) {
      if (!active[prior]) continue;
      if (safeText(list[prior]?.no, 30) !== voidRef) continue;
      active[prior] = false;
      break;
    }
  }
  return list.filter((_receipt, index) => active[index]);
}

